# Builds lib/alert-names.ts from the JMA multilingual dictionary (気象情報等に関する多言語辞書, updated 2026-03-26).
# Source: https://www.data.jma.go.jp/developer/multilingual.html  (xlsx snapshot in money-research/japan-alert-sources/)
import json, sys, openpyxl
SRC = sys.argv[1] if len(sys.argv) > 1 else "/workspace/money-research/japan-alert-sources/jma_multilingual_2026-03-26.xlsx"
LANGS = ["en", "zh-CN", "zh-TW", "ko", "pt", "es", "id", "vi", "tl", "th", "ne", "km", "my", "mn"]
TERMS = [
  "レベル５大雨特別警報", "レベル５土砂災害特別警報", "レベル５氾濫特別警報", "レベル５高潮特別警報",
  "レベル４大雨危険警報", "レベル４土砂災害危険警報", "レベル４氾濫危険警報", "レベル４高潮危険警報",
  "レベル３大雨警報", "レベル３土砂災害警報", "レベル３氾濫警報", "レベル３高潮警報",
  "レベル２大雨注意報", "レベル２土砂災害注意報", "レベル２氾濫注意報", "レベル２高潮注意報",
  "暴風特別警報", "暴風雪特別警報", "大雪特別警報", "波浪特別警報", "暴風警報", "暴風雪警報", "大雪警報", "波浪警報",
  "強風注意報", "風雪注意報", "大雪注意報", "波浪注意報", "雷注意報", "濃霧注意報", "乾燥注意報", "なだれ注意報",
  "着氷注意報", "着雪注意報", "融雪注意報", "霜注意報", "低温注意報",
  "緊急地震速報", "先ほど発表した緊急地震速報を取り消します", "震度速報", "震源・震度に関する情報",
  "大津波警報", "津波警報", "津波注意報", "津波予報",
  "南海トラフ地震臨時情報", "巨大地震警戒", "巨大地震注意", "調査中", "調査終了", "北海道・三陸沖後発地震注意情報",
  "噴火速報", "噴火警報", "レベル５（避難）", "レベル４（高齢者等避難）", "レベル３（入山規制）", "レベル２（火口周辺規制）",
  "熱中症警戒アラート", "土砂災害警戒情報", "竜巻注意情報", "氾濫危険情報", "氾濫発生情報",
]
wb = openpyxl.load_workbook(SRC, read_only=True)
rows = list(wb["多言語辞書（本体）"].iter_rows(values_only=True))
out = {}
for t in TERMS:
    hit = next((r for r in rows[1:] if r[3] and str(r[3]).strip() == t), None)
    if not hit:
        print("MISSING", t, file=sys.stderr); continue
    out[t] = {lang: str(hit[4 + i]).strip() for i, lang in enumerate(LANGS) if hit[4 + i]}
body = json.dumps(out, ensure_ascii=False, indent=1)
open("lib/alert-names.ts", "w").write(
    "// Generated by scripts/build-names.py from the JMA multilingual dictionary (updated 2026-03-26). Do not edit by hand.\n"
    "// Source: https://www.data.jma.go.jp/developer/multilingual.html\n"
    f"export const NAME_LANGS = {json.dumps(LANGS)} as const;\n"
    "export type NameLang = (typeof NAME_LANGS)[number];\n"
    "export const DICTIONARY_UPDATED = \"2026-03-26\";\n"
    f"export const JMA_NAMES: Record<string, Partial<Record<NameLang, string>>> = {body};\n")
print(len(out), "terms")
